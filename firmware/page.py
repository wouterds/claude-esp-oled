"""Turns assets/portal.html into a header holding it gzipped.

Generated into the build directory rather than into src, for the same reason
version.py writes where it does: building a tree should not dirty it.

Compressed here because the board cannot afford not to. The page is twenty-two
kilobytes and the socket it goes out through holds under six, so sending it as
it stands is four buffers each waiting on the radio - and on a link that is
losing packets, any one of those waits is where the page stops. Gzipped it is
under seven, every browser unpacks it without being asked twice, and the board
never has to: it only ever hands the bytes over.
"""

import gzip
import os

Import("env")  # noqa: F821  - injected by PlatformIO

HERE = env.subst("$PROJECT_DIR")  # noqa: F821
ASSET = os.path.join(HERE, "assets", "portal.html")

with open(ASSET, "rb") as handle:
    page = handle.read()
# No timestamp in it, so the same page is the same bytes on every build.
packed = gzip.compress(page, 9, mtime=0)

rows = [
    "  " + ", ".join("0x{:02x}".format(b) for b in packed[at : at + 16]) + ","
    for at in range(0, len(packed), 16)
]
body = (
    "// Generated by page.py from assets/portal.html. Do not edit.\n"
    "#pragma once\n\n"
    "#include <Arduino.h>\n\n"
    "static const uint8_t PAGE[] PROGMEM = {\n" + "\n".join(rows) + "\n};\n"
)

out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
path = os.path.join(out_dir, "page.h")
# Only when it has actually changed, so the header's mtime does not move every
# build and take everything that includes it along.
if not os.path.exists(path) or open(path, encoding="utf-8").read() != body:
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(body)

env.Append(CPPPATH=[out_dir])  # noqa: F821
print("page.py: {} bytes of page, {} gzipped".format(len(page), len(packed)))
